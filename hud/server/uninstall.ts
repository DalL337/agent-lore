// `lore uninstall`: remove what `lore init` added, in the main checkout and
// every linked worktree, and nothing of the owner's (ruling D4).
//
// Removed: the files LORE generated; its blocks in the owner's files (their
// text stays exactly as it was); its hooks in settings files (a file of the
// owner's that LORE merged into goes back to its copy in .lore/originals/
// when nothing else in it changed); the runtime and launchers; the git hook,
// or its block in the owner's; the ignore rules. lore/ goes too while it is
// still the suite as LORE copied it.
//
// Kept unless --all: lore/ once the owner has adapted it, and the board and
// any other files of theirs in .lore/. Their ignore rules stay, so they stay
// private. Journals (.research/) are never touched, nor anything outside the
// repository (Claude's memory folder, Codex's trust settings).

import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { hasLoreHooks, mainDirectories, mergeDirectories, mergeHooks } from './agents.ts';
import { git } from './config.ts';
import {
  checkouts,
  CODEX_DESCRIPTION,
  CONFIG_KEYS,
  fileState,
  finish,
  HOOK_BEGIN,
  HOOK_END,
  IGNORE_BEGIN,
  IGNORE_END,
  locate,
  MD_BEGIN,
  MD_END,
  ORIGINALS,
  planner,
  readConfig,
  readText,
  removeBlock,
  slash,
  upsertBlock,
  walk,
  type InitPlan,
  type Planner,
} from './init.ts';

export interface UninstallOptions {
  cwd: string;
  /** The suite LORE was installed from, when .lore/runtime/ no longer holds a copy. */
  suiteDir: string;
  /** Also remove the owner's adapted lore/ and their files in .lore/ (the board). Never journals. */
  all?: boolean;
}

/** JSON equal, whatever the key order. */
function sameJson(text: string, value: unknown): boolean {
  const canon = (v: unknown): unknown =>
    Array.isArray(v) ? v.map(canon) : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).sort(([a], [b]) => a.localeCompare(b)).map(([k, x]) => [k, canon(x)])) : v;
  try {
    return JSON.stringify(canon(JSON.parse(text.replace(/^﻿/, '')))) === JSON.stringify(canon(value));
  } catch {
    return false;
  }
}

/** Every folder above these files, up to and including `top`. */
function foldersOf(files: string[], top: string): string[] {
  const out = new Set<string>([top]);
  for (const f of files) for (let d = path.posix.dirname(f); d.startsWith(top) && d !== top; d = path.posix.dirname(d)) out.add(d);
  return [...out];
}

/** LORE's files, blocks and hooks in one checkout's agent files. */
function agentFiles(p: Planner, prune: Set<string>) {
  for (const rel of ['AGENTS.md', 'AGENTS.override.md', 'CLAUDE.md', 'CLAUDE.local.md']) {
    const state = fileState(p.root, rel);
    if (!state.exists || state.tracked) continue;
    if (state.ours) {
      p.drop(rel, 'generated by LORE');
    } else if (state.text!.includes(MD_BEGIN)) {
      const rest = removeBlock(state.text!, MD_BEGIN, MD_END);
      if (rest.trim()) p.put(rel, rest, 'LORE’s block removed; your text stays as it was', { ignore: false });
      else p.drop(rel, 'it held only LORE’s block');
    }
  }
  for (const rel of ['.claude/settings.local.json', '.codex/hooks.json']) {
    const state = fileState(p.root, rel);
    if (!state.exists || state.tracked || !hasLoreHooks(state.text)) continue;
    let merged = mergeHooks(state.text, {});
    if (merged.error === undefined) merged = mergeDirectories(merged.text, [], mainDirectories(p.main));
    if (merged.error !== undefined) {
      p.warnings.push(`${rel} is ${merged.error}: remove LORE’s hooks from it by hand.`);
      continue;
    }
    const doc = JSON.parse(merged.text) as Record<string, unknown>;
    const original = p.root === p.main ? readText(path.join(p.main, ORIGINALS, rel)) : null;
    if (original !== null && sameJson(original, doc)) {
      p.put(rel, original, 'restored as it was before LORE', { ignore: false });
    } else if (Object.entries(doc).every(([k, v]) => k === 'description' && v === CODEX_DESCRIPTION)) {
      p.drop(rel, 'it held only LORE’s hooks');
      prune.add(path.posix.dirname(rel));
    } else {
      p.put(rel, merged.text, 'LORE’s hooks removed; your settings stay', { ignore: false });
    }
  }
}

/** What `lore uninstall` would do: one plan per checkout, the main one first. */
export function planUninstall(options: UninstallOptions): InitPlan[] {
  const { main } = locate(options.cwd);
  const all = options.all === true;
  const plans = checkouts(main).map((dir) => {
    const p = planner(dir, main);
    const prune = new Set<string>();
    agentFiles(p, prune);
    if (dir !== main && fileState(dir, 'lore/LORE.md').ours) {
      p.drop('lore/LORE.md', 'this worktree’s copy of LORE.md');
      prune.add('lore');
    }
    return { p, prune };
  });
  const { p, prune } = plans[0];
  const kept: string[] = [];

  // lore/: gone while it is the suite as copied; the owner's once adapted.
  let loreKept = false;
  const loreDir = path.join(main, 'lore');
  if (existsSync(loreDir)) {
    const runtimeSuite = path.join(main, '.lore', 'runtime', 'suite', 'lore');
    const reference = existsSync(runtimeSuite) ? runtimeSuite : options.suiteDir;
    const files = walk(loreDir);
    const changed = files.filter((rel) => {
      const theirs = path.join(reference, rel);
      return !existsSync(theirs) || !readFileSync(theirs).equals(readFileSync(path.join(loreDir, rel)));
    });
    const tracked = (git(main, ['ls-files', '--', 'lore']) ?? '') !== '';
    if (tracked) {
      loreKept = true;
      kept.push('lore/: committed to the repository, so it stays; remove it through git if you want it gone');
    } else if (changed.length && !all) {
      loreKept = true;
      kept.push(`lore/: your adaptations of LORE (${changed.length} file${changed.length === 1 ? '' : 's'} changed or added); \`lore uninstall --all\` removes it too`);
    } else {
      for (const rel of files) p.drop(`lore/${rel}`, changed.length ? 'your adapted LORE (--all)' : 'LORE, as it was copied', 'lore/');
      for (const d of foldersOf(files.map((f) => `lore/${f}`), 'lore')) prune.add(d);
    }
  }

  // .lore/: LORE's runtime, launchers and logs go; the board and other files of the owner's stay.
  const dot = path.join(main, '.lore');
  let dotKept = false;
  if (existsSync(dot)) {
    const files = walk(dot);
    const theirs: string[] = [];
    for (const rel of files) {
      const full = `.lore/${rel}`;
      if (rel.startsWith('runtime/')) p.drop(full, 'LORE’s runtime', '.lore/runtime/');
      else if (rel.startsWith('originals/')) p.drop(full, 'your files as they were, now restored', ORIGINALS);
      else if (['lore.mjs', 'hud', 'hud.cmd', 'hud.log', 'hud.json', 'hud.starting'].includes(rel)) p.drop(full, 'LORE’s launchers and HUD log', '.lore/ launchers, log');
      else if (rel === 'config.json' && !all) {
        let config: Record<string, unknown> | null = null;
        try {
          config = readConfig(main).config;
        } catch {
          theirs.push('config.json (not valid JSON, so LORE left it)');
        }
        if (config) {
          const rest = Object.fromEntries(Object.entries(config).filter(([k, v]) => !CONFIG_KEYS.includes(k) || (k === 'autostart' && v === false)));
          const original = readText(path.join(main, ORIGINALS, '.lore/config.json'));
          if (original !== null && sameJson(original, rest)) {
            p.put(full, original, 'restored as it was before LORE', { ignore: false });
            theirs.push('config.json (as it was before LORE)');
          } else if (!Object.keys(rest).length) p.drop(full, 'it held only LORE’s settings');
          else {
            p.put(full, `${JSON.stringify(rest, null, 2)}\n`, 'LORE’s settings removed; yours stay', { ignore: false });
            theirs.push('config.json (your settings)');
          }
        }
      } else if (all) p.drop(full, 'yours (--all)', '.lore/ (--all)');
      else theirs.push(rel);
    }
    if (theirs.length) {
      dotKept = true;
      kept.push(`.lore/: ${theirs.join(', ')}; yours, so it stays (\`lore uninstall --all\` removes it)`);
    }
    for (const d of foldersOf(files.map((f) => `.lore/${f}`), '.lore')) prune.add(d);
  }

  // The git hook, or LORE's block in the owner's.
  const hooks = git(main, ['rev-parse', '--path-format=absolute', '--git-path', 'hooks']);
  const hookFile = hooks ? path.join(hooks, 'post-checkout') : null;
  const hookText = hookFile ? readText(hookFile) : null;
  if (hookFile && hookText?.includes(HOOK_BEGIN)) {
    const rel = slash(path.relative(main, hookFile));
    const rest = removeBlock(hookText, HOOK_BEGIN, HOOK_END);
    if (/^(#![^\n]*)?\s*$/.test(rest)) p.drop(rel, 'LORE’s git hook');
    else p.put(rel, rest, 'LORE’s block removed from your hook', { ignore: false });
  }

  // Ignore rules: only those for what stays.
  const keepRules = [...(loreKept && !(git(main, ['ls-files', '--', 'lore']) ?? '') ? ['/lore/'] : []), ...(dotKept ? ['/.lore/'] : []), ...(existsSync(path.join(main, '.research')) ? ['/.research/'] : [])];
  if (existsSync(path.join(main, '.research'))) kept.push('.research/: your journals, never touched; still ignored');
  const common = git(main, ['rev-parse', '--path-format=absolute', '--git-common-dir']) ?? path.join(main, '.git');
  for (const file of [path.join(common, 'info', 'exclude'), path.join(main, '.gitignore')]) {
    const text = readText(file);
    if (!text?.includes(IGNORE_BEGIN)) continue;
    const rel = slash(path.relative(main, file));
    const next = keepRules.length ? upsertBlock(text, IGNORE_BEGIN, IGNORE_END, keepRules.join('\n')) : removeBlock(text, IGNORE_BEGIN, IGNORE_END);
    const why = keepRules.length ? `ignore rules only for what stays (${keepRules.join(' ')})` : 'LORE’s ignore rules removed';
    if (!next && rel === '.gitignore' && !fileState(main, rel).tracked) p.drop(rel, why);
    else p.put(rel, next, why, { ignore: false });
  }

  return plans.map(({ p: plan, prune: folders }, i) => ({
    ...finish(plan, { worktree: i > 0, notes: i > 0 ? [`linked worktree ${slash(plan.root)}`] : [], installed: true, sync: true, commit: false, agents: [], runtime: null }),
    prune: [...folders],
    kept: i === 0 ? kept : [],
  }));
}
