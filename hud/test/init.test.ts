test('run in a linked worktree: LORE goes in the main checkout', async () => {
  const main = await repo({ 'README.md': '# app\n' });
  const wt = `${main}-feature`;
  git(main, 'worktree', 'add', '-q', '-b', 'feature', wt);
  try {
    const plan = run(wt);
    assert.equal(path.resolve(plan.root), path.resolve(main));
    assert.match(plan.notes[0], /linked worktree/);
    assert.ok(existsSync(path.join(main, 'lore', 'LORE.md')));
    assert.ok(!existsSync(path.join(wt, 'lore')), 'the worktree hook (step 4) links LORE in; init does not copy it');
    assert.equal(status(main), '');
    assert.equal(status(wt), '');
  } finally {
    git(main, 'worktree', 'remove', '--force', wt);
  }
});

