test('--dry-run writes nothing and says what it would do', async () => {
  const dir = await repo({ 'README.md': '# app\n' });
  const before = await exclude(dir);
  const plan = planInit({ cwd: dir, suiteDir: SUITE });
  assert.equal(status(dir), '');
  assert.ok(!existsSync(path.join(dir, 'lore')));
  assert.equal(await exclude(dir), before);
  const lines = describePlan(plan, true).join('\n');
  assert.match(lines, /lore\/\s+would copy \d+ files/);
  assert.match(lines, /AGENTS\.md\s+would create/);
});

test('lore/ is the owner’s once installed: edits and deletions survive another init', async () => {
  const dir = await repo();
  run(dir);
  const memory = path.join(dir, 'lore', 'policies', 'memory.md');
  await writeFile(memory, '# Memory, our way\n');
  await rm(path.join(dir, 'lore', 'policies', 'creative.md'));
  const again = planInit({ cwd: dir, suiteDir: SUITE });
  assert.equal(pending(again), false);
  assert.match(describePlan(again).join('\n'), /already installed/);
  assert.equal(await readFile(memory, 'utf8'), '# Memory, our way\n');
  assert.ok(!existsSync(path.join(dir, 'lore', 'policies', 'creative.md')));
});

test('a lore/ folder that is not LORE’s stops init; an interrupted copy resumes', async () => {
  const theirs = await repo({ 'lore/dragons.md': '# Dragons of the north\n' });
  assert.throws(() => planInit({ cwd: theirs, suiteDir: SUITE }), (err: Error) => err instanceof InitError && /lore\/dragons\.md/.test(err.message));

  const partial = await repo();
  await mkdir(path.join(partial, 'lore', 'policies'), { recursive: true });
  await writeFile(path.join(partial, 'lore', 'policies', 'git.md'), await readFile(path.join(SUITE, 'policies', 'git.md')));
  const plan = installClean(partial);
  const copied = plan.changes.filter((c) => c.path.startsWith('lore/')).map((c) => c.path);
  assert.ok(!copied.includes('lore/policies/git.md') && copied.includes('lore/LORE.md'));
});

test('sync and check: editing lore/LORE.md makes the generated copies stale until `lore sync`', async () => {
  const dir = await repo({ 'AGENTS.md': '# Acme\n' });
  run(dir);
  const lore = path.join(dir, 'lore', 'LORE.md');
  await writeFile(lore, `${await readFile(lore, 'utf8')}\n## Acme notes\n\nShip on Fridays.\n`);

  const check = checkRepo({ cwd: dir, suiteDir: SUITE });
  assert.deepEqual(check.problems, ['AGENTS.override.md is out of date: `lore sync` regenerates it']);
  run(dir, { sync: true });
  assert.match(await read(dir, 'AGENTS.override.md'), /Ship on Fridays/);
  assert.deepEqual(checkRepo({ cwd: dir, suiteDir: SUITE }).problems, []);
});

test('check: missing ignore rules show up as LORE files git would list', async () => {
  const dir = await repo();
  run(dir);
  const text = await exclude(dir);
  await writeFile(path.join(dir, '.git', 'info', 'exclude'), removeBlock(text, text.match(/# >>> LORE.*/)![0], '# <<< LORE'));
  const check = checkRepo({ cwd: dir, suiteDir: SUITE });
  assert.match(check.problems.join('\n'), /\.git\/info\/exclude is out of date/);
  assert.ok(check.visible.includes('lore/LORE.md') && check.visible.includes('AGENTS.md') && check.visible.includes('CLAUDE.md'), check.visible.join(', '));
  run(dir, { sync: true });
  assert.equal(status(dir), '');
});

