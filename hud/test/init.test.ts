test('marked blocks: added once, replaced in place, removed cleanly', () => {
  const add = upsertBlock('mine\n', '# >', '# <', 'one');
  assert.equal(add, 'mine\n\n# >\none\n# <\n');
  assert.equal(upsertBlock(add, '# >', '# <', 'one'), add);
  assert.equal(upsertBlock(`${add}after\n`, '# >', '# <', 'two'), 'mine\n\n# >\ntwo\n# <\nafter\n');
  assert.equal(removeBlock(add, '# >', '# <'), 'mine\n');
  assert.equal(removeBlock(`${add}after\n`, '# >', '# <'), 'mine\n\nafter\n');
  assert.equal(upsertBlock(null, '# >', '# <', 'x'), '# >\nx\n# <\n');
});
