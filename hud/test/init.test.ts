test('when the project later commits an AGENTS.md, sync moves LORE aside and removes what it no longer needs', async () => {
  const dir = await repo();
  run(dir);
  // A teammate's AGENTS.md arrives (a pull replaces the ignored, generated one).
  await writeFile(path.join(dir, 'AGENTS.md'), '# Acme, from the team\n');
  git(dir, 'add', '-f', 'AGENTS.md');
  git(dir, 'commit', '-q', '-m', 'agents');

  const plan = run(dir, { sync: true });
  assert.deepEqual(kinds(plan), { 'AGENTS.override.md': 'create', 'CLAUDE.md': 'remove', 'CLAUDE.local.md': 'create', '.git/info/exclude': 'update' });
  assert.ok(!existsSync(path.join(dir, 'CLAUDE.md')));
  assert.match(await read(dir, 'CLAUDE.local.md'), /@AGENTS\.md\n@lore\/LORE\.md/);
  const rules = await exclude(dir);
  assert.doesNotMatch(rules, /^\/AGENTS\.md$/m);
  assert.doesNotMatch(rules, /^\/CLAUDE\.md$/m);
  assert.equal(status(dir), '');
  assert.equal(pending(planInit({ cwd: dir, suiteDir: SUITE })), false);
});

test('--commit: lore/ is left for the owner to commit; the private rules go in .gitignore too, and the choice sticks', async () => {
  const dir = await repo({ '.gitignore': 'node_modules/\n' });
  run(dir); // private first, then switch
  const plan = run(dir, { commit: true });
  assert.equal(plan.commit, true);
  assert.equal(kinds(plan)['.git/info/exclude'], 'update', 'lore/ comes out of the shared exclude block');
  const local = await exclude(dir);
  assert.doesNotMatch(local, /^\/lore\/$/m);
  assert.match(local, /^\/\.lore\/$/m, 'every checkout stays covered, whatever its branch’s .gitignore says');
  const gitignore = await read(dir, '.gitignore');
  assert.ok(gitignore.startsWith('node_modules/\n\n# >>> LORE'));
  assert.doesNotMatch(gitignore, /^\/lore\/$/m);
  assert.match(gitignore, /^\/\.research\/$/m, 'journals are never committed');

  const shown = git(dir, 'status', '--porcelain', '--untracked-files=all').split('\n').filter(Boolean).map((l) => l.slice(3));
  assert.ok(shown.includes('.gitignore') && shown.includes('lore/LORE.md'));
  assert.ok(!shown.some((p) => /^(AGENTS|CLAUDE)\.md$/.test(p)), 'generated files stay private');
  assert.equal(pending(planInit({ cwd: dir, suiteDir: SUITE })), false, 'a later init without --commit keeps sharing');
  assert.deepEqual(checkRepo({ cwd: dir, suiteDir: SUITE }).visible, [], 'lore/ showing is expected when shared');
});

